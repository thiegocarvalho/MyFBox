export function createInitialVaultPayload(withSampleData: boolean, vaultName: string = 'Cofre Pessoal'): VaultPayload {
  return {
    version: 1,
    updatedAt: new Date().toISOString(),
    accounts: withSampleData ? structuredClone(DEFAULT_ACCOUNTS) : structuredClone(EMPTY_ACCOUNTS),
    categories: structuredClone(DEFAULT_CATEGORIES),
    transactions: withSampleData ? buildSampleTransactions(new Date()) : [],
    settings: {
      currency: 'BRL',
      autoLockMinutes: 15,
      hideValuesByDefault: false,
      vaultName: vaultName.trim() || 'Cofre Pessoal',
    },
  };
}
